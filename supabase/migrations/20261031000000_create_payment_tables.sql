create table if not exists public.balances (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  type varchar not null,
  device varchar not null,
  date date not null,
  amount float8 not null check (amount >= 0)
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  type varchar not null,
  tran_id varchar,
  time time not null,
  charge float8 not null default 0 check (charge >= 0),
  amount float8 not null check (amount > 0),
  device varchar not null,
  note varchar,
  date date not null,
  created_by uuid not null default auth.uid() references auth.users(id) on delete cascade
);

create index if not exists balances_date_created_at_idx on public.balances (date, created_at desc);
create index if not exists payments_date_time_idx on public.payments (date, time desc);

alter table public.balances enable row level security;
alter table public.payments enable row level security;

create policy "Authenticated users can read balances"
  on public.balances for select to authenticated using (true);
create policy "Authenticated users can add balances"
  on public.balances for insert to authenticated with check (true);
create policy "Authenticated users can read payments"
  on public.payments for select to authenticated using (true);
create policy "Users can add their own payments"
  on public.payments for insert to authenticated with check (created_by = (select auth.uid()));
